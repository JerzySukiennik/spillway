// Solo run with a stocked inventory: places every item, fires power-ups, measures frame time.
import { createRequire } from 'node:module';
const require = createRequire('/Users/jurek/openclaw/node_modules/');
const { chromium } = require('playwright-core');

const OUT = process.argv[2] || '.';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1680, height: 1050 }, deviceScaleFactor: 2 });
const logs = [];
page.on('console', (m) => { if (!/404|Failed to load/.test(m.text())) logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}\n${e.stack}`));
await page.goto('http://localhost:8643/');
await page.evaluate(() => { localStorage.setItem('spillway.solo', JSON.stringify({ lv: 0, econ: { money: 999, up: { ink: 1, tank: 1, pump: 1 }, inv: { me: { funnel: 2, pipe: 1, tramp: 1, fan: 1, lift: 1, ice: 1, magnet: 1, refill: 1 } } } })); });
await page.reload();
await page.waitForTimeout(500);
await page.click('button.solo');
await page.waitForTimeout(500);
await page.evaluate(() => document.querySelector('.go-btn').click());
await page.waitForTimeout(2400);
const sc = await page.evaluate(() => window.spillway.screen.scale);
const S = (wx, wy, cam = -60) => [(wx - cam) * sc, wy * sc];
const line = async (pts) => { await page.mouse.move(...S(...pts[0])); await page.mouse.down(); for (const p of pts.slice(1)) { const [x, y] = S(...p); await page.mouse.move(x, y, { steps: 30 }); } await page.mouse.up(); };
await line([[400, 236], [900, 340]]);
await page.keyboard.press('3');
await page.mouse.move(...S(1000, 420));
await page.waitForTimeout(150);
await page.screenshot({ path: `${OUT}/it-01-ghost.png` });
await page.mouse.click(...S(1000, 420));
await page.keyboard.press('4');
await page.keyboard.press('e'); await page.keyboard.press('e');
await page.mouse.click(...S(1180, 520));
await page.keyboard.press('5');
await page.keyboard.press('q'); await page.keyboard.press('q');
await page.mouse.click(...S(1400, 700));
await page.keyboard.press('6');
await page.mouse.click(...S(300, 760));
await page.keyboard.press('7');
for (let i = 0; i < 6; i++) await page.keyboard.press('q');
await page.mouse.click(...S(700, 800));
await page.waitForTimeout(400);
await page.keyboard.down('Space');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${OUT}/it-02-items.png` });
await page.keyboard.press('9');
await page.mouse.click(...S(1100, 650));
await page.waitForTimeout(1200);
await page.screenshot({ path: `${OUT}/it-03-magnet.png` });
await page.keyboard.press('8');
await page.waitForTimeout(700);
await page.screenshot({ path: `${OUT}/it-04-ice.png` });
await page.keyboard.up('Space');
const perf = await page.evaluate(async () => {
  const s = window.spillway.screen;
  const times = [];
  const orig = s.frame.bind(s);
  s.frame = (t) => { const a = performance.now(); orig(t); times.push(performance.now() - a); };
  await new Promise((r) => setTimeout(r, 3000));
  s.frame = orig;
  times.sort((a, b) => a - b);
  return { frames: times.length, median: times[times.length >> 1].toFixed(2), p95: times[Math.floor(times.length * 0.95)].toFixed(2), n: s.world.fluid.n, items: s.world.items.map((i) => i.k), inv: s.world.inv[0], ink: Math.round(s.world.ink[0]) };
});
logs.push('[perf] ' + JSON.stringify(perf));
console.log(logs.join('\n'));
await browser.close();
